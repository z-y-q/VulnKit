"use strict";
// 灵眸 - Svelte/SvelteKit Detection Inject Script
(function () {
    'use strict';
    const __vk_token = document.currentScript
        ? document.currentScript.dataset.vkToken || ''
        : '';
    const result = {
        detected: false,
        version: '',
        variant: '',
        components: [],
        stores: [],
        isSvelteKit: false,
        routingMode: '',
        signals: [],
    };
    // Svelte dev mode global
    if (window.__svelte) {
        result.detected = true;
        result.signals.push('__svelte global detected');
    }
    // SvelteKit global
    if (window.__sveltekit) {
        result.detected = true;
        result.isSvelteKit = true;
        result.signals.push('__sveltekit global detected');
    }
    // DOM class pattern: svelte-{hash} generated by Svelte compiler
    const svelteClasses = {};
    const allElements = document.querySelectorAll('*');
    for (let i = 0; i < allElements.length; i++) {
        const el = allElements[i];
        if (el.nodeType !== 1)
            continue;
        const cls = el.className;
        if (typeof cls !== 'string')
            continue;
        const parts = cls.split(/\s+/);
        for (let j = 0; j < parts.length; j++) {
            const match = parts[j].match(/^svelte-([a-z0-9]+)$/i);
            if (match && !svelteClasses[match[0]]) {
                svelteClasses[match[0]] = true;
            }
        }
    }
    const classKeys = Object.keys(svelteClasses);
    if (classKeys.length > 0) {
        result.detected = true;
        result.components = classKeys.slice(0, 50);
        result.signals.push(classKeys.length + ' Svelte scoped CSS classes');
    }
    // SvelteKit specific: data-sveltekit attributes
    const kitElements = document.querySelectorAll('[data-sveltekit-preload-data], [data-sveltekit-reload], [data-sveltekit-ignore], [class*="sveltekit"]');
    if (kitElements.length > 0) {
        result.detected = true;
        result.isSvelteKit = true;
        result.signals.push('SvelteKit data attributes found');
    }
    // SvelteKit: check for SvelteKit navigation/routing
    try {
        if (window.__sveltekit ||
            document.querySelector('[data-sveltekit-preload-data], [data-sveltekit-reload]')) {
            result.isSvelteKit = true;
            result.routingMode = 'SvelteKit file-based routing';
        }
    }
    catch (_) {
        /* skip */
    }
    // Script src detection
    const scripts = document.querySelectorAll('script[src]');
    scripts.forEach(function (s) {
        const src = s.src || '';
        if (/svelte\/internal/i.test(src)) {
            result.detected = true;
            result.signals.push('svelte/internal script: ' + src.split('/').pop());
        }
        if (/svelte/i.test(src) && !/sveltekit/i.test(src)) {
            result.detected = true;
            result.signals.push('Svelte script: ' + src.split('/').pop());
        }
        if (/sveltekit/i.test(src)) {
            result.detected = true;
            result.isSvelteKit = true;
            result.signals.push('SvelteKit script: ' + src.split('/').pop());
        }
        // Version extraction from .svelte-kit or node_modules/.svelte-kit
        const versionMatch = src.match(/svelte@(\d+\.\d+\.\d+)/i);
        if (versionMatch && !result.version) {
            result.version = versionMatch[1];
        }
        const kitVersionMatch = src.match(/@sveltejs\/kit@(\d+\.\d+\.\d+)/i);
        if (kitVersionMatch) {
            result.isSvelteKit = true;
            if (!result.version)
                result.version = kitVersionMatch[1];
        }
    });
    // Body text detection (lightweight regex)
    try {
        const bodyText = document.body ? document.body.innerHTML.substring(0, 50000) : '';
        if (/__sveltekit/i.test(bodyText)) {
            result.detected = true;
            result.isSvelteKit = true;
            if (result.signals.indexOf('__sveltekit in body') === -1) {
                result.signals.push('__sveltekit in body text');
            }
        }
        if (/svelte-[a-z0-9]+/i.test(bodyText) && !result.detected) {
            result.detected = true;
        }
    }
    catch (_) {
        /* skip */
    }
    // Comment node detection: <!-- svelte-xxx -->
    try {
        const iterator = document.createNodeIterator(document, NodeFilter.SHOW_COMMENT);
        let commentNode;
        while ((commentNode = iterator.nextNode())) {
            if (/svelte/i.test(commentNode.nodeValue || '')) {
                result.detected = true;
                result.signals.push('Svelte comment node: ' + (commentNode.nodeValue || '').substring(0, 80));
                break;
            }
        }
    }
    catch (_) {
        /* skip */
    }
    // Determine variant
    if (result.isSvelteKit) {
        result.variant = 'SvelteKit';
    }
    else if (result.detected) {
        result.variant = 'Svelte';
    }
    window.postMessage({ __vk_svelte_detect: true, __vk_token: __vk_token, result: result }, location.origin);
})();
